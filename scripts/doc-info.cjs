// Document links and missing details for the editing panel ("מעקב עריכה").
//
// For every item code it finds:
//   - the read-only origin document in "מסמכי DOCx מוכנים לפרסום" (by the code in its file name), and
//   - the missing details in the formatted source document (formatted-source/<CODE>.docx):
//     every paragraph with yellow-highlighted text ("טקסט מסומן בצהוב = מידע חסר").
// The result is written into index.html as NB_DOC_INFO (between the generated markers).
// It is not item content, so the content version does not change.
//
//   node scripts/doc-info.cjs
//
// The changes check runs it too (scripts/check-source-changes.cjs), so the panel follows
// edits to the formatted documents. Run node wordpress/build.cjs before committing.

const fs = require('node:fs');
const path = require('node:path');
const zlib = require('node:zlib');

const root = path.resolve(__dirname, '..');
const docsDir = path.join(root, 'formatted-source');
const originDir = path.join(root, 'מסמכי DOCx מוכנים לפרסום');
const indexPath = path.join(root, 'index.html');
// The project folder in OneDrive: the same place the formatted document links point to.
const BASE = 'https://marathon051-my.sharepoint.com/personal/liat_i_we-com_co_il/Documents/'
  + ['שולחן העבודה', 'Kira', 'KnowledgeBase'].map(encodeURIComponent).join('/') + '/';
const START = '// <generated:doc-info>';
const END = '// </generated:doc-info>';

function readEntry(file, name) {
  const a = fs.readFileSync(file);
  const end = a.lastIndexOf(Buffer.from([0x50, 0x4b, 0x05, 0x06]));
  if (end < 0) return '';
  let cur = a.readUInt32LE(end + 16);
  for (let i = 0; i < a.readUInt16LE(end + 10); i++) {
    const method = a.readUInt16LE(cur + 10), size = a.readUInt32LE(cur + 20);
    const nl = a.readUInt16LE(cur + 28), xl = a.readUInt16LE(cur + 30), cl = a.readUInt16LE(cur + 32), off = a.readUInt32LE(cur + 42);
    if (a.subarray(cur + 46, cur + 46 + nl).toString('utf8') === name) {
      const s = off + 30 + a.readUInt16LE(off + 26) + a.readUInt16LE(off + 28);
      const c = a.subarray(s, s + size);
      return (method === 8 ? zlib.inflateRawSync(c) : c).toString('utf8');
    }
    cur += 46 + nl + xl + cl;
  }
  return '';
}
const decode = s => s.replace(/&quot;/g, '"').replace(/&apos;/g, "'").replace(/&lt;/g, '<').replace(/&gt;/g, '>')
  .replace(/&#(\d+);/g, (_, d) => String.fromCodePoint(+d)).replace(/&amp;/g, '&');
const runText = r => decode((r.match(/<w:t\b[^>]*>[\s\S]*?<\/w:t>/g) || []).map(t => t.replace(/<[^>]+>/g, '')).join(''));

// Paragraphs with yellow-highlighted text: the highlighted part of each.
function missingDetails(file) {
  const xml = readEntry(file, 'word/document.xml');
  const out = [];
  for (const p of xml.matchAll(/<w:p\b[^>]*>([\s\S]*?)<\/w:p>/g)) {
    let text = '';
    for (const r of p[1].matchAll(/<w:r\b[^>]*>([\s\S]*?)<\/w:r>/g))
      if (/<w:highlight w:val="yellow"\/>/.test(r[1])) text += runText(r[1]);
    text = text.replace(/\s+/g, ' ').trim();
    if (text) out.push(text);
  }
  return out;
}

// The item code in an origin file name ("R31 - …", "O 55", "0-06" for O-06).
function codeOf(name) {
  const m = /(?:^|[^A-Za-z])([MROESTIH0])\s*[-_]?\s*(\d{2,3})(?!\d)/.exec(path.basename(name, '.docx'));
  return m ? (m[1] === '0' ? 'O' : m[1]) + '-' + m[2] : null;
}
function originFiles() {
  const found = {};
  (function walk(dir) {
    if (!fs.existsSync(dir)) return;
    for (const f of fs.readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, f.name);
      if (f.isDirectory()) walk(p);
      else if (/\.docx$/i.test(f.name) && !f.name.startsWith('~$')) {
        const code = codeOf(f.name);
        if (!code) continue;
        const rel = path.relative(originDir, p).split(path.sep);
        const size = fs.statSync(p).size, draft = rel.some(x => /טיוטה/.test(x));
        // A real file outside the draft subfolders wins over an empty one or a draft.
        const rank = (size > 0 ? 2 : 0) + (draft ? 0 : 1);
        if (!found[code] || rank > found[code].rank) found[code] = { rel, rank };
      }
    }
  })(originDir);
  return found;
}

function build() {
  const info = {};
  const origins = originFiles();
  for (const [code, o] of Object.entries(origins)) {
    info[code] = { origin: { name: o.rel[o.rel.length - 1],
      url: BASE + [path.basename(originDir)].concat(o.rel).map(encodeURIComponent).join('/') + '?web=1' } };
  }
  if (fs.existsSync(docsDir)) {
    for (const n of fs.readdirSync(docsDir).filter(n => /^[A-Z]-\d{2,3}\.docx$/.test(n))) {
      const code = n.slice(0, -5);
      (info[code] = info[code] || {}).missing = missingDetails(path.join(docsDir, n));
    }
  }
  return info;
}

function write() {
  const info = build();
  const sorted = {};
  Object.keys(info).sort().forEach(k => { sorted[k] = info[k]; });
  const block = `${START}\n// Generated by scripts/doc-info.cjs: origin document links and missing details per item code.\nvar NB_DOC_INFO = ${JSON.stringify(sorted)};\n${END}`;
  let html = fs.readFileSync(indexPath, 'utf8');
  const a = html.indexOf(START), b = html.indexOf(END);
  if (a < 0 || b < 0) throw new Error('index.html has no generated doc-info block.');
  html = html.slice(0, a) + block + html.slice(b + END.length);
  fs.writeFileSync(indexPath, html);
  const codes = Object.keys(sorted);
  const missing = codes.filter(c => sorted[c].missing && sorted[c].missing.length);
  console.log(`Doc info: ${codes.filter(c => sorted[c].origin).length} origin documents, ${codes.filter(c => sorted[c].missing).length} formatted documents, ${missing.length} with missing details.`);
}

if (require.main === module) write();
module.exports = { write };
